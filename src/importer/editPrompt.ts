// 2026-11-18：「复制给 AI 修改」—— 把 App 当前的行程（标准格式）连同修改规则一起复制，
// 用户贴到自己的 ChatGPT / Claude，说要怎么改，再把 AI 输出的完整行程贴回「重新导入」。
// 重新导入时按 日期|类型|标题 对上原来的项目，完成状态和证明文件会保留，所以要求 AI 不改没动的项目的标题。

export function buildEditPrompt(md: string): string {
  return `你是旅行行程修改助手。下面【当前行程】是「旅程 Rundown」App 导出的行程，格式是 App 规定的，请严格保持。
我会在最后告诉你要怎么改。请按我的要求修改，然后输出修改后的完整行程。

规则：
1. 把整份结果放进一个代码块（三个反引号加 text 开头）里输出，代码块之外不要写任何解释，里面不要加 Markdown 加粗。
2. 输出完整行程，不能只输出改动的部分；没要求改的内容原样保留，一个字都不要动。
3. 格式完全照抄：# 旅程标题、## 每一天、### [类型] 时间 标题、- 字段: 值。类型只能是 flight / lodging / spot / transit / meal / note。日期一律写「日-月-年」。
4. 没要求改的行程项，标题和类型不要改（App 靠「日期 + 类型 + 标题」认出原来的项目，改了标题会丢掉它的完成状态和证明文件）。
5. 新增的行程项按同样格式写；不要编造订单号、航班号、预订状态；不确定的字段省略。
6. 每一天都要保留，日期要连续。改了出发日期或天数时，所有日期一起顺延。

【当前行程】
\`\`\`text
${md.trim()}
\`\`\`

【我要的修改】
（在这里写你要怎么改，例如：第 3 天下午加一个景点；把第 5 天的住宿换成札幌站附近）`;
}
